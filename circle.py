import math


def area(r):
    '''
    Функция принимает одно целое число - радиус окружности.

    Возвращает S - Площадь круга.

    Например при вызове area(5), функция вернёт S = 78.53981633974483.
    '''
    return math.pi * r * r


def perimeter(r):
    '''
    Функция принимает одно целое число - радиус окружности.

    Возвращает P - Длину окружности (периметр).

    Например при вызове perimeter(5), функция вернёт P = 31.41592653589793.
    '''
    return 2 * math.pi * r

