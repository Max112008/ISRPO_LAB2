def area(a, b): 
    '''
    Функция принимает два целых числа - длины сторон прямоугольника.

    Возвращает S - Площадь прямоугольника.

    Например при вызове area(4, 7), функция вернёт S = 28.
    '''
    return a * b 

def perimeter(a, b): 
    '''
    Функция принимает два целых числа - длины сторон прямоугольника.

    Возвращает P - Периметр прямоугольника.

    Например при вызове perimeter(4, 7), функция вернёт P = 22.
    '''
    return 2 * (a + b)